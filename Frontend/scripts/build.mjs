import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const envPath = '.env';
let apiUrl = '/api';

try {
  const envFile = readFileSync(envPath, 'utf8');
  const line = envFile.split(/\r?\n/).find((entry) => entry.startsWith('FRONTEND_API_URL='));
  if (line) apiUrl = line.slice('FRONTEND_API_URL='.length).trim();
} catch {
  // .env is optional in CI and Docker; the same-origin default is intentional.
}

if (!apiUrl || !/^\/(?!\/)|^https?:\/\//.test(apiUrl)) {
  throw new Error('FRONTEND_API_URL must be /api or an absolute http(s) URL');
}

writeFileSync(
  'src/environments/environment.production.generated.ts',
  `// Generated by scripts/build.mjs.\nexport const productionApiUrl = ${JSON.stringify(apiUrl)};\n`,
);

const cliPath = fileURLToPath(new URL('../node_modules/@angular/cli/bin/ng.js', import.meta.url));
const result = spawnSync(process.execPath, [cliPath, 'build'], { stdio: 'inherit' });
process.exit(result.status ?? 1);
